-- Clientes, historial de estados, delivery (zonas y repartidores) y confirmación de pedidos.
-- Se aplica en public y en cada esquema restaurant_N. Es idempotente.

CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',              -- solo dígitos, con código de país (595…)
  ruc TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  orders_count INTEGER NOT NULL DEFAULT 0 CHECK (orders_count >= 0),
  total_spent BIGINT NOT NULL DEFAULT 0 CHECK (total_spent >= 0),
  last_order_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS customers_phone_unique ON customers (phone) WHERE phone <> '';
CREATE UNIQUE INDEX IF NOT EXISTS customers_ruc_unique ON customers (ruc) WHERE ruc <> '';
CREATE INDEX IF NOT EXISTS customers_name ON customers (lower(name));
CREATE INDEX IF NOT EXISTS customers_last_order ON customers (last_order_at DESC NULLS LAST);

CREATE TABLE IF NOT EXISTS delivery_zones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  areas TEXT NOT NULL DEFAULT '',              -- barrios o ciudades que cubre
  fee BIGINT NOT NULL DEFAULT 0 CHECK (fee >= 0),
  free_over BIGINT CHECK (free_over IS NULL OR free_over >= 0),
  eta_minutes INTEGER CHECK (eta_minutes IS NULL OR eta_minutes BETWEEN 1 AND 600),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS delivery_zones_name_unique ON delivery_zones (lower(name));

CREATE TABLE IF NOT EXISTS couriers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  vehicle TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL;
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'pos';
ALTER TABLE service_orders DROP CONSTRAINT IF EXISTS service_orders_source_check;
ALTER TABLE service_orders ADD CONSTRAINT service_orders_source_check CHECK (source IN ('pos', 'table_qr', 'whatsapp', 'web'));
-- confirmation: los pedidos remotos (WhatsApp, web) entran «pending» y el local los confirma o rechaza.
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS confirmation TEXT NOT NULL DEFAULT 'confirmed';
ALTER TABLE service_orders DROP CONSTRAINT IF EXISTS service_orders_confirmation_check;
ALTER TABLE service_orders ADD CONSTRAINT service_orders_confirmation_check CHECK (confirmation IN ('pending', 'confirmed', 'rejected'));
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS delivery_zone_id BIGINT REFERENCES delivery_zones(id) ON DELETE SET NULL;
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS delivery_zone_name TEXT NOT NULL DEFAULT '';
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS delivery_fee BIGINT NOT NULL DEFAULT 0;
ALTER TABLE service_orders DROP CONSTRAINT IF EXISTS service_orders_delivery_fee_check;
ALTER TABLE service_orders ADD CONSTRAINT service_orders_delivery_fee_check CHECK (delivery_fee >= 0);
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS delivery_address TEXT NOT NULL DEFAULT '';
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS courier_id BIGINT REFERENCES couriers(id) ON DELETE SET NULL;
ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS courier_name TEXT NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS service_orders_customer ON service_orders (customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS service_orders_pending ON service_orders (created_at) WHERE status = 'open' AND confirmation = 'pending';

-- Historial de cada orden: quién hizo qué y cuándo. Nunca se edita, solo se agrega.
CREATE TABLE IF NOT EXISTS order_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES service_orders(id) ON DELETE CASCADE,
  ticket_id BIGINT,
  event TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  actor_id BIGINT REFERENCES public.app_users(id) ON DELETE SET NULL,
  actor_name TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS order_status_history_order ON order_status_history (order_id, created_at);
