-- Salones y mesas de cada restaurante. El QR no contiene información privada.
CREATE TABLE IF NOT EXISTS dining_rooms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  image_data TEXT NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS dining_tables (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id BIGINT NOT NULL REFERENCES dining_rooms(id) ON DELETE RESTRICT,
  label TEXT NOT NULL,
  seats INTEGER NOT NULL DEFAULT 4 CHECK (seats BETWEEN 1 AND 30),
  shape TEXT NOT NULL DEFAULT 'round' CHECK (shape IN ('round', 'square', 'rectangular')),
  code TEXT NOT NULL UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (room_id, label)
);
CREATE INDEX IF NOT EXISTS dining_tables_room ON dining_tables (room_id, is_active);

ALTER TABLE service_orders ADD COLUMN IF NOT EXISTS table_id BIGINT REFERENCES dining_tables(id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX IF NOT EXISTS service_orders_one_open_per_table
  ON service_orders (table_id) WHERE status = 'open' AND table_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS guest_order_requests (
  request_id UUID PRIMARY KEY,
  table_id BIGINT NOT NULL REFERENCES dining_tables(id) ON DELETE RESTRICT,
  order_id BIGINT REFERENCES service_orders(id) ON DELETE SET NULL,
  ticket_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Conservamos las referencias escritas antes de instalar los salones.
INSERT INTO dining_rooms (name, description)
SELECT 'Salón principal', 'Mesas del local'
WHERE NOT EXISTS (SELECT 1 FROM dining_rooms);
