-- Facturas de compra a proveedores (insumos y mercadería): cabecera con proveedor, número, timbrado, fecha,
-- condición y totales con IVA; ítems con descripción, categoría, unidad, cantidad, costo e IVA.
-- Un ítem puede vincularse a un producto del menú para sumar su stock. Se cargan a mano o escaneando la factura (Niro IA).

CREATE TABLE IF NOT EXISTS purchase_invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
  supplier_name TEXT NOT NULL DEFAULT '',
  supplier_ruc TEXT NOT NULL DEFAULT '',
  invoice_number TEXT NOT NULL DEFAULT '',
  stamp TEXT NOT NULL DEFAULT '',
  invoice_date DATE NOT NULL,
  condition TEXT NOT NULL DEFAULT 'cash' CHECK (condition IN ('cash', 'credit')),
  due_date DATE,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
  exempt BIGINT NOT NULL DEFAULT 0,
  taxed5 BIGINT NOT NULL DEFAULT 0,
  taxed10 BIGINT NOT NULL DEFAULT 0,
  tax5 BIGINT NOT NULL DEFAULT 0,
  tax10 BIGINT NOT NULL DEFAULT 0,
  total BIGINT NOT NULL DEFAULT 0 CHECK (total >= 0),
  notes TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'scan')),
  cash_movement_id BIGINT,
  created_by BIGINT,
  created_by_name TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  cancelled_at TIMESTAMPTZ,
  cancelled_by_name TEXT NOT NULL DEFAULT '',
  cancel_reason TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS purchase_invoices_date ON purchase_invoices (invoice_date DESC, id DESC);
CREATE INDEX IF NOT EXISTS purchase_invoices_supplier ON purchase_invoices (supplier_id, invoice_date DESC);
-- La misma factura del mismo proveedor no se carga dos veces.
CREATE UNIQUE INDEX IF NOT EXISTS purchase_invoices_unique_number ON purchase_invoices (supplier_ruc, invoice_number)
  WHERE status = 'active' AND supplier_ruc <> '' AND invoice_number <> '';

CREATE TABLE IF NOT EXISTS purchase_invoice_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id BIGINT NOT NULL REFERENCES purchase_invoices(id) ON DELETE CASCADE,
  position INTEGER NOT NULL DEFAULT 0,
  description TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT '',
  unit TEXT NOT NULL DEFAULT 'u',
  quantity NUMERIC(14, 3) NOT NULL CHECK (quantity > 0),
  unit_cost NUMERIC(16, 2) NOT NULL CHECK (unit_cost >= 0),
  tax_rate SMALLINT NOT NULL DEFAULT 10 CHECK (tax_rate IN (0, 5, 10)),
  total BIGINT NOT NULL CHECK (total >= 0),
  product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
  stock_added INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS purchase_invoice_items_invoice ON purchase_invoice_items (invoice_id, position);
CREATE INDEX IF NOT EXISTS purchase_invoice_items_product ON purchase_invoice_items (product_id) WHERE product_id IS NOT NULL;

-- Tiempo real: las pantallas de compras se actualizan solas.
CREATE OR REPLACE TRIGGER restopos_live AFTER INSERT OR UPDATE OR DELETE ON purchase_invoices FOR EACH ROW EXECUTE FUNCTION public.restopos_notify();
