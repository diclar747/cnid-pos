-- Llamados desde la mesa (mozo, cuenta) y suscripciones a notificaciones push.
-- Se aplica en public y en cada esquema restaurant_N. Es idempotente.

CREATE TABLE IF NOT EXISTS table_calls (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id BIGINT NOT NULL REFERENCES dining_tables(id) ON DELETE CASCADE,
  table_label TEXT NOT NULL DEFAULT '',
  kind TEXT NOT NULL DEFAULT 'waiter' CHECK (kind IN ('waiter', 'bill')),
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'attended')),
  note TEXT NOT NULL DEFAULT '',
  attended_by BIGINT REFERENCES public.app_users(id) ON DELETE SET NULL,
  attended_by_name TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  attended_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS table_calls_open ON table_calls (created_at) WHERE status = 'open';
-- Un solo llamado abierto por mesa y tipo: repetir el botón no genera llamados duplicados.
CREATE UNIQUE INDEX IF NOT EXISTS table_calls_one_open ON table_calls (table_id, kind) WHERE status = 'open';

-- scope 'order': el cliente sigue su pedido (order_id). scope 'staff': personal del local (user_id).
CREATE TABLE IF NOT EXISTS push_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint TEXT NOT NULL,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  scope TEXT NOT NULL CHECK (scope IN ('order', 'staff')),
  order_id BIGINT REFERENCES service_orders(id) ON DELETE CASCADE,
  table_id BIGINT REFERENCES dining_tables(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES public.app_users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_sent_at TIMESTAMPTZ,
  UNIQUE (endpoint, scope)
);
CREATE INDEX IF NOT EXISTS push_subscriptions_order ON push_subscriptions (order_id) WHERE scope = 'order';
CREATE INDEX IF NOT EXISTS push_subscriptions_staff ON push_subscriptions (scope) WHERE scope = 'staff';

-- Claves VAPID del sistema (compartidas por todos los restaurantes).
CREATE TABLE IF NOT EXISTS public.system_settings (
  key TEXT PRIMARY KEY,
  value JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
